-- ชื่อ "คลังข้อมูล" กลับมาใช้ (รุ่น 2569-11-27-2)
-- เมนูย่อย /posts ใน "ข้อมูลข่าวสาร" และหัวข้อหน้าแรก ที่รุ่น 2569-11-27 เปลี่ยนเป็น
-- "ประกาศ/คำสั่ง/ระเบียบ/หลักเกณฑ์/บันทึกข้อความ/คู่มือ" กลับเป็น "คลังข้อมูล"
-- แก้เฉพาะรายการที่ยังเป็นชื่อยาวนั้น ถ้าผู้ดูแลเปลี่ยนชื่อเองแล้ว จะไม่เขียนทับ
UPDATE _emdash_menu_items SET label = 'คลังข้อมูล'
WHERE menu_id = (SELECT id FROM _emdash_menus WHERE name = 'primary')
	AND custom_url = '/posts' AND label = 'ประกาศ/คำสั่ง/ระเบียบ/หลักเกณฑ์/บันทึกข้อความ/คู่มือ';
UPDATE ec_site_info SET heading_documents = 'คลังข้อมูล'
WHERE heading_documents = 'ประกาศ/คำสั่ง/ระเบียบ/หลักเกณฑ์/บันทึกข้อความ/คู่มือ';
